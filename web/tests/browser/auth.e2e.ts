import { test, expect } from '@playwright/test';

test('login, cookies HttpOnly, renovacao, recarga, troca de senha e logout com API e PostgreSQL reais', async ({ page, context }) => {
  const api = process.env.SECURITY_BROWSER_API!;
  const password = 'Navegador@123456';
  const changed = 'Alterada@12345678';
  const violations: string[] = [];
  await page.exposeFunction('recordCspViolation', (message: string) => { violations.push(message); });
  await page.addInitScript(() => {
    document.addEventListener('securitypolicyviolation', event => {
      const violation = event as SecurityPolicyViolationEvent;
      (window as any).recordCspViolation(violation.violatedDirective + ': ' + violation.blockedURI);
    });
  });
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('browser@test.com');
  await page.getByLabel('Senha', { exact: true }).fill(password);
  const login = page.waitForResponse(r => r.url() === api + '/sessions' && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  const response = await login;
  expect(response.status()).toBe(200);
  const body = await response.json();
  expect(body).toHaveProperty('user');
  expect(body).not.toHaveProperty('token');
  expect(body).not.toHaveProperty('refreshToken');
  await expect(page).toHaveURL(/\/app\/dashboard/);
  const first = await context.cookies(api + '/sessions');
  const access = first.find(c => c.name === 'sa_access')!;
  const refresh = first.find(c => c.name === 'sa_refresh')!;
  expect(access.httpOnly).toBe(true); expect(refresh.httpOnly).toBe(true);
  expect(refresh.path).toBe('/sessions');
  expect(await page.evaluate(() => document.cookie)).not.toContain('sa_access');
  expect(await page.evaluate(() => document.cookie)).not.toContain('sa_refresh');
  expect(await page.evaluate(() => localStorage.getItem('auth_token'))).toBeNull();
  expect(await page.evaluate(() => localStorage.getItem('user'))).toBeNull();
  const rawClaims = JSON.parse(Buffer.from(refresh.value.split('.')[1]!, 'base64url').toString());
  expect(rawClaims).not.toHaveProperty('user'); expect(rawClaims.sub).toBe('1');
  for (const key of ['email', 'nome', 'usuario', 'nivelAcesso']) expect(rawClaims).not.toHaveProperty(key);
  // Delete only the access cookie to reproduce expiry while preserving refresh.
  await context.clearCookies({ name: 'sa_access' });
  const renewal = page.waitForResponse(r => r.url() === api + '/sessions/refresh-token');
  await page.reload();
  expect((await renewal).status()).toBe(200);
  await expect(page).toHaveURL(/\/app\/dashboard/);
  expect((await context.cookies(api + '/sessions')).find(c => c.name === 'sa_refresh')!.value).not.toBe(refresh.value);
  await page.locator('.mf-toolbar-btn').last().click();
  await page.locator('.user-menu-list').getByText('Sair', { exact: true }).click();
  await expect(page).toHaveURL(/\/login/);
  await page.goto('/redefinir-senha#token=' + process.env.SECURITY_BROWSER_RESET_TOKEN!);
  await expect(page).toHaveURL(/\/redefinir-senha$/);
  const recovered = 'Recuperada@123456';
  await page.getByLabel('Nova senha', { exact: true }).fill(recovered);
  await page.getByLabel('Repita a nova senha', { exact: true }).fill(recovered);
  await page.getByRole('button', { name: 'Salvar nova senha' }).click();
  await expect(page.getByText('Senha alterada. Entre com a nova senha.', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Ir para o login', exact: true }).click();
  await page.getByLabel('Email', { exact: true }).fill('browser@test.com');
  await page.getByLabel('Senha', { exact: true }).fill(recovered);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page).toHaveURL(/\/app\/dashboard/);
  await page.goto('/app/configuracoes/alterar-senha');
  await page.getByLabel('Senha atual', { exact: true }).fill(recovered);
  await page.getByLabel('Nova senha', { exact: true }).fill(changed);
  await page.getByLabel('Confirmar nova senha', { exact: true }).fill(changed);
  await page.getByRole('button', { name: 'Salvar nova senha' }).click();
  await expect(page).toHaveURL(/\/login/);
  expect((await context.cookies(api + '/sessions')).filter(c => c.name.startsWith('mf_'))).toHaveLength(0);
  await page.getByLabel('Email', { exact: true }).fill('browser@test.com');
  await page.getByLabel('Senha', { exact: true }).fill(changed);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page).toHaveURL(/\/app\/dashboard/);
  await page.locator('.mf-toolbar-btn').last().click();
  await page.locator('.user-menu-list').getByText('Sair', { exact: true }).click();
  await expect(page).toHaveURL(/\/login/);
  expect((await context.cookies(api + '/sessions')).filter(c => c.name.startsWith('mf_'))).toHaveLength(0);
  await page.goto('/app/reunioes');
  await expect(page).toHaveURL(/\/login/);
  expect(violations).toEqual([]);
});
